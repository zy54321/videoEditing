#Requires -Version 5.1
Set-StrictMode -Version Latest

function Get-ProductPayloadRoot {
    param([string]$SourceRoot = (Split-Path -Parent (Split-Path -Parent $PSScriptRoot)))
    $root = Join-Path $SourceRoot 'payload'
    if (-not (Test-Path -LiteralPath $root -PathType Container)) {
        throw "Product payload root not found: $root"
    }
    return (Resolve-Path -LiteralPath $root).Path
}

function Get-ProductIgnorePatterns {
    param([string]$PayloadRoot)
    $ignoreFile = Join-Path $PayloadRoot '.productignore'
    $patterns = @('**/__pycache__/**', '**/*.pyc')
    if (Test-Path -LiteralPath $ignoreFile) {
        $lines = Get-Content -LiteralPath $ignoreFile -Encoding UTF8 |
            ForEach-Object { $_.Trim() } |
            Where-Object { $_ -and -not $_.StartsWith('#') }
        if ($lines) { $patterns = $lines }
    }
    return $patterns
}

function Test-ProductIgnoreMatch {
    param([string]$RelativePath, [string[]]$Patterns)
    $norm = $RelativePath.Replace('\', '/').ToLowerInvariant()
    if ($norm -match '/__pycache__/') { return $true }
    if ($norm -match '\.pyc$') { return $true }
    foreach ($pat in $Patterns) {
        $p = $pat.Trim().ToLowerInvariant()
        if ($p -eq '**/__pycache__/**' -or $p -eq '**/*.pyc') { continue }
        $rx = '^' + ($p.Replace('.', '\.').Replace('**/', '(?:.*/)?').Replace('*', '[^/]*')) + '$'
        if ($norm -match $rx) { return $true }
    }
    return $false
}

function Get-ProductFileInventory {
    param([string]$PayloadRoot = (Get-ProductPayloadRoot))
    $patterns = Get-ProductIgnorePatterns -PayloadRoot $PayloadRoot
    $files = Get-ChildItem -LiteralPath $PayloadRoot -Recurse -File | Sort-Object FullName
    $list = New-Object System.Collections.Generic.List[string]
    foreach ($f in $files) {
        $rel = $f.FullName.Substring($PayloadRoot.Length).TrimStart('\', '/')
        if (Test-ProductIgnoreMatch -RelativePath $rel -Patterns $patterns) { continue }
        $list.Add($rel.Replace('/', '\'))
    }
    return $list.ToArray()
}

function Get-ProductInventoryHash {
    param([string[]]$Inventory)
    $joined = ($Inventory | ForEach-Object { $_ }) -join "`n"
    $bytes = [System.Text.Encoding]::UTF8.GetBytes($joined)
    $sha = [System.Security.Cryptography.SHA256]::Create()
    return ([BitConverter]::ToString($sha.ComputeHash($bytes)).Replace('-', '').ToLowerInvariant())
}

function Write-InstallerProductFilesGenerated {
    param(
        [string]$SourceRoot,
        [string[]]$Inventory,
        [string]$OutPath
    )
    $sb = New-Object System.Text.StringBuilder
    $sb.AppendLine('# AUTO-GENERATED by ProductInventory.ps1 — do not edit manually.') | Out-Null
    $sb.AppendLine('# Authority: source/payload/ (see .productignore)') | Out-Null
    $sb.AppendLine('$ProductFiles = @(') | Out-Null
    for ($i = 0; $i -lt $Inventory.Count; $i++) {
        $escaped = $Inventory[$i].Replace("'", "''")
        $suffix = if ($i -lt $Inventory.Count - 1) { ',' } else { '' }
        $sb.AppendLine("    '$escaped'$suffix") | Out-Null
    }
    $sb.AppendLine(')') | Out-Null
    $utf8 = New-Object System.Text.UTF8Encoding $false
    [System.IO.File]::WriteAllText($OutPath, $sb.ToString(), $utf8)
}

function Sync-ProductInstallerInventory {
    param([string]$SourceRoot = (Split-Path -Parent (Split-Path -Parent $PSScriptRoot)))
    $payloadRoot = Get-ProductPayloadRoot -SourceRoot $SourceRoot
    $inventory = Get-ProductFileInventory -PayloadRoot $payloadRoot
    $outPath = Join-Path $SourceRoot 'installer\product-files.generated.ps1'
    Write-InstallerProductFilesGenerated -SourceRoot $SourceRoot -Inventory $inventory -OutPath $outPath
    return @{
        Inventory = $inventory
        Path = $outPath
        Hash = (Get-ProductInventoryHash -Inventory $inventory)
        Count = $inventory.Count
    }
}

function Test-ProductInstallerInSync {
    param([string]$SourceRoot = (Split-Path -Parent (Split-Path -Parent $PSScriptRoot)))
    $payloadRoot = Get-ProductPayloadRoot -SourceRoot $SourceRoot
    $expected = Get-ProductFileInventory -PayloadRoot $payloadRoot
    $genPath = Join-Path $SourceRoot 'installer\product-files.generated.ps1'
    if (-not (Test-Path -LiteralPath $genPath)) { return $false }
    $content = Get-Content -LiteralPath $genPath -Raw -Encoding UTF8
    $actual = [regex]::Matches($content, "'([^']+)'") | ForEach-Object { $_.Groups[1].Value }
    if ($actual.Count -ne $expected.Count) { return $false }
    for ($i = 0; $i -lt $expected.Count; $i++) {
        if ($actual[$i] -ne $expected[$i]) { return $false }
    }
    return $true
}
